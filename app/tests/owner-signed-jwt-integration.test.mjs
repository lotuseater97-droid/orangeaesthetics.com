import test from "node:test";
import assert from "node:assert/strict";
import {generateKeyPair,exportJWK,createLocalJWKSet,SignJWT} from "jose";
import {createOidcOwnerVerifier} from "../lib/oidc-owner-verifier.mjs";
import {createOwnerCatalogApproval} from "../lib/owner-catalog-approval.mjs";
import {createOwnerCatalogHttpHandler} from "../lib/owner-catalog-http-handler.mjs";
const issuer="https://auth.example.test",audience="orange-private-api",origin="https://orangeaesthetics.com";
const itemId="00000000-0000-4000-8000-000000000001";
test("signed owner JWT reaches audited approval; revoked role and forged tokens denied",async()=>{
 const {publicKey,privateKey}=await generateKeyPair("RS256");
 const jwk=await exportJWK(publicKey);jwk.kid="test-owner-key";jwk.alg="RS256";jwk.use="sig";
 const keySet=createLocalJWKSet({keys:[jwk]});
 const claims={issuer,audience};
 const sign=(subject,override={})=>new SignJWT({scope:"catalog:approve",...override}).setProtectedHeader({alg:"RS256",kid:jwk.kid}).setIssuer(issuer).setAudience(audience).setSubject(subject).setIssuedAt().setExpirationTime("10m").sign(privateKey);
 let active=true,approvals=0;
 const query=async(sql,params)=>{
  if(sql.includes("FROM orange_app.staff_roles"))return {rows:active?[{role:"owner",active:true}]:[]};
  if(sql.includes("set_catalog_checkout_approval")){approvals++;assert.deepEqual(params.slice(0,4),["owner-subject",itemId,true,false]);assert.match(params[4],/^[0-9a-f-]{36}$/);return {rows:[{applied:true}]}};
  throw Error("Unexpected query");
 };
 const verifyOwner=createOidcOwnerVerifier({...claims,jwksUrl:issuer+"/jwks",query,keySet});
 const approveCatalog=createOwnerCatalogApproval({query,verifyOwner});
 const handle=createOwnerCatalogHttpHandler({approveCatalog,origin,enabled:true});
 const send=async token=>handle({method:"POST",headers:{origin,"content-type":"application/json",authorization:"Bearer "+token},rawBody:JSON.stringify({itemId,approved:true,requiresClinicalReview:false})});
 const valid=await sign("owner-subject");
 assert.equal((await send(valid)).status,200);
 assert.equal(approvals,1);
 active=false;
 assert.equal((await send(valid)).status,403);
 assert.equal(approvals,1);
 active=true;
 const wrongAudience=new SignJWT({}).setProtectedHeader({alg:"RS256",kid:jwk.kid}).setIssuer(issuer).setAudience("wrong-api").setSubject("owner-subject").setIssuedAt().setExpirationTime("10m");
 assert.equal((await send(await wrongAudience.sign(privateKey))).status,403);
 assert.equal(approvals,1);
 const {privateKey:otherKey}=await generateKeyPair("RS256");
 const forged=new SignJWT({}).setProtectedHeader({alg:"RS256",kid:jwk.kid}).setIssuer(issuer).setAudience(audience).setSubject("owner-subject").setIssuedAt().setExpirationTime("10m");
 assert.equal((await send(await forged.sign(otherKey))).status,403);
 assert.equal(approvals,1);
});
